#!/usr/bin/env python3
"""Irreducibility certificates for the polynomials (TUCore.polys).

For each Q (descending integer coefficients) find a prime p not dividing the leading coefficient such that
Q mod p is irreducible over F_p, certified by gcd(Q mod p, X^(p^k) - X) = 1 for 1 <= k <= deg/2:
for each such k we emit r_k = X^(p^k) mod Q and Bezout cofactors u_k, v_k with
u_k * Q + v_k * (r_k - X) = 1 in F_p[X]. Lists are ascending coefficient lists with entries in [0, p).

Standard library only. Usage: python3 -I tools/tu_irred_cert.py DATA.lean OUT.lean [OUT.json]
"""
import json
import re
import sys


def trim(a):
    a = list(a)
    while a and a[-1] == 0:
        a.pop()
    return a


def add(p, a, b):
    n = max(len(a), len(b))
    return trim([((a[i] if i < len(a) else 0) + (b[i] if i < len(b) else 0)) % p for i in range(n)])


def sub(p, a, b):
    n = max(len(a), len(b))
    return trim([((a[i] if i < len(a) else 0) - (b[i] if i < len(b) else 0)) % p for i in range(n)])


def mul(p, a, b):
    if not a or not b:
        return []
    r = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        if x:
            for j, y in enumerate(b):
                r[i + j] = (r[i + j] + x * y) % p
    return trim(r)


def divmod_poly(p, f, q):
    f = trim(f)
    q = trim(q)
    inv = pow(q[-1], p - 2, p)
    rem = list(f)
    if len(rem) < len(q):
        return [], rem
    quot = [0] * (len(rem) - len(q) + 1)
    for i in range(len(rem) - len(q), -1, -1):
        c = rem[i + len(q) - 1] * inv % p
        quot[i] = c
        if c:
            for j, y in enumerate(q):
                rem[i + j] = (rem[i + j] - c * y) % p
    return trim(quot), trim(rem)


def mod(p, f, q):
    return divmod_poly(p, f, q)[1]


def powmod(p, r, e, q):
    result = [1]
    base = mod(p, r, q)
    while e:
        if e & 1:
            result = mod(p, mul(p, result, base), q)
        base = mod(p, mul(p, base, base), q)
        e >>= 1
    return result


def ext_gcd(p, a, b):
    """Return (g, s, t) with s a + t b = g (g monic or [])."""
    r0, r1 = trim(a), trim(b)
    s0, s1 = [1], []
    t0, t1 = [], [1]
    while r1:
        qq, rr = divmod_poly(p, r0, r1)
        r0, r1 = r1, rr
        s0, s1 = s1, sub(p, s0, mul(p, qq, s1))
        t0, t1 = t1, sub(p, t0, mul(p, qq, t1))
    if r0:
        c = pow(r0[-1], p - 2, p)
        r0 = [x * c % p for x in r0]
        s0 = trim([x * c % p for x in s0])
        t0 = trim([x * c % p for x in t0])
    return r0, s0, t0


def primes(limit):
    sieve = [True] * (limit + 1)
    sieve[0] = sieve[1] = False
    for i in range(2, int(limit ** 0.5) + 1):
        if sieve[i]:
            for j in range(i * i, limit + 1, i):
                sieve[j] = False
    return [i for i in range(limit + 1) if sieve[i]]


def cert_for(desc, p):
    lead = desc[0] % p
    if lead == 0:
        return None
    q = trim([a % p for a in reversed(desc)])
    n = len(desc) - 1
    X = [0, 1]
    out = []
    r = X
    for k in range(1, n // 2 + 1):
        r = powmod(p, r, p, q)
        g, u, v = ext_gcd(p, q, sub(p, r, X))
        if g != [1]:
            return None
        # check u q + v (r - X) = 1
        assert add(p, mul(p, u, q), mul(p, v, sub(p, r, X))) == [1]
        out.append((r, u, v))
    return out


def parse_polys(path):
    src = open(path).read()
    m = re.search(r"def polys : List \(List Int\) := (\[.*?\]\])\s*$", src, re.M)
    return json.loads(m.group(1))


def lean_list(l):
    return "[" + ", ".join(str(x) for x in l) + "]"


def main():
    data, out_lean = sys.argv[1], sys.argv[2]
    out_json = sys.argv[3] if len(sys.argv) > 3 else None
    polys = parse_polys(data)
    plist = primes(1000)
    results = []
    for j, desc in enumerate(polys):
        found = None
        for p in plist:
            c = cert_for(desc, p)
            if c is not None:
                found = (p, c)
                break
        if found is None:
            print(f"Q_{j}: NO prime below 1000 gives an irreducible reduction (deg {len(desc) - 1})")
            results.append(None)
        else:
            p, c = found
            size = sum(len(r) + len(u) + len(v) for (r, u, v) in c)
            print(f"Q_{j}: deg {len(desc) - 1}, p = {p}, {len(c)} steps, {size} coefficients")
            results.append({"j": j, "p": p, "cert": c})
    if any(r is None for r in results):
        sys.exit(1)
    lines = []
    lines.append("import TUCore.Irred")
    lines.append("import TUCore.Data")
    lines.append("")
    lines.append("/-! Irreducibility certificates for the polynomials `TUCore.polys`: for each `j` a prime `p` and,")
    lines.append("for `1 ≤ k ≤ deg/2`, `(r_k, u_k, v_k)` with `r_k ≡ X^(p^k)` and `u_k Q + v_k (r_k - X) = 1` mod `p`.")
    lines.append("Generated by tools/tu_irred_cert.py. -/")
    lines.append("")
    lines.append("namespace TUCore")
    lines.append("")
    lines.append("/-- The primes. -/")
    lines.append("def irredPrimes : List Nat := " + lean_list([r["p"] for r in results]))
    lines.append("")
    for r in results:
        j = r["j"]
        entries = ", ".join("(" + lean_list(a) + ", " + lean_list(b) + ", " + lean_list(c) + ")" for (a, b, c) in r["cert"])
        lines.append(f"/-- Certificate for `Q_{j}` modulo `{r['p']}`. -/")
        lines.append(f"def irredCert{j} : List (List Nat × List Nat × List Nat) := [{entries}]")
        lines.append("")
    lines.append("end TUCore")
    open(out_lean, "w").write("\n".join(lines) + "\n")
    if out_json:
        json.dump(results, open(out_json, "w"))


if __name__ == "__main__":
    main()
