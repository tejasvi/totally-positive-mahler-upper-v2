"""Generate TUCore/Data.lean (core Lean, no imports) from the certificate cert_tp_up_c34e6e53.json
(read-only input): polynomials, weights b_j, nodes, G values, X and the claim v, as exact integers.
usage: python3 -I gen_tu_data.py CERT.json OUT_Data.lean"""
import json, sys, hashlib
from fractions import Fraction as Fr
cert_path, out = sys.argv[1], sys.argv[2]
raw = open(cert_path, 'rb').read(); sha = hashlib.sha256(raw).hexdigest()
c = json.loads(raw)
assert c['format'] == 'tpmahler-upper-v1'
DEN = 400
polys = c['polys']
bw = [Fr(x) for x in c['b']]
assert all(x > 0 and x.denominator & (x.denominator - 1) == 0 for x in bw)
nodes = [Fr(x) for x in c['nodes']]; assert all((x * DEN).denominator == 1 for x in nodes)
n = [int(x * DEN) for x in nodes]
G = [Fr(x) for x in c['G']]
GS = max(x.denominator for x in G).bit_length() - 1
g = [int(x * (1 << GS)) for x in G]; assert all(Fr(gi, 1 << GS) == Gi for gi, Gi in zip(g, G))
X = Fr(c['X']); v = Fr(c['v'])
assert X.denominator == 1
def lst(xs): return '[' + ', '.join(str(x) for x in xs) + ']'
L = []
L.append('/-! Data of the certificate `cert_tp_up_c34e6e53.json`, generated by tools/gen_tu_data.py.')
L.append(f'Input SHA-256: {sha}. Core Lean only. -/')
L.append('')
L.append('set_option maxRecDepth 200000')
L.append('')
L.append('namespace TUCore')
L.append('')
L.append('/-- The polynomials `Q_j`, coefficients from the leading one down to the constant term. -/')
L.append('def polys : List (List Int) := ' + lst([lst(p) for p in polys]))
L.append('/-- The weights `b_j = bNum_j / 2^bSh_j` (all positive). -/')
L.append('def bNum : List Nat := ' + lst([x.numerator for x in bw]))
L.append('def bSh : List Nat := ' + lst([x.denominator.bit_length() - 1 for x in bw]))
L.append('/-- The nodes `e_i = nodes_i / 400`. -/')
L.append('def nodes : List Nat := ' + lst(n))
L.append('/-- `G_i = gvals_i / 2^GS`. -/')
L.append(f'def GS : Nat := {GS}')
L.append('def gvals : List Nat := ' + lst(g))
L.append('/-- `X` (the interval `[0, X]` of Smith\'s theorem) and the claim `v = vNum / vDen`. -/')
L.append(f'def Xcap : Nat := {X.numerator}')
L.append(f'def vNum : Nat := {v.numerator}')
L.append(f'def vDen : Nat := {v.denominator}')
L.append('')
L.append('end TUCore')
L.append('')
open(out, 'w').write('\n'.join(L))
print('polys', len(polys), 'nodes', len(n), 'GS', GS, 'sha', sha[:8])
