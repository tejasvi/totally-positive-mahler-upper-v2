"""Emit TUCore/Leaves.lean (core Lean) from the (C3) tiling (tools/tu_check_ref.py output): the leaves sorted by
position, as a List of TPCore.Leaf records, from e_0 = 45/400 to 3526/400 (one node spacing past e_N). Untrusted
hints: the checker verifies everything.
usage: python3 -I gen_tu_leaves.py leaves.json OUT.lean"""
import json, sys, hashlib
from fractions import Fraction as Fr
DEN = 400
raw = open(sys.argv[1], 'rb').read(); sha = hashlib.sha256(raw).hexdigest()
d = json.loads(raw)
L = [(Fr(l['Xp'], DEN << l['k']), 0, l['Xp'], l['Xq'], l['k'], bool(l['x0q']), l['mask']) for l in d['chord']]
L += [(Fr(w['Xu'], DEN << w['k']), 1, w['Xu'], w['Xv'], w['k'], False, 0) for w in d['windows']]
L.sort(key=lambda t: t[0])
for a, b in zip(L, L[1:]):
    assert Fr(a[3], DEN << a[4]) == Fr(b[2], DEN << b[4]), (a, b)
assert L[0][0] == Fr(45, DEN), L[0]
xt = Fr(L[-1][3], DEN << L[-1][4]); assert xt == Fr(3526, DEN), xt
out = ['import TUCore.Check', '',
       f'/-! Leaves of the (C3) tiling, generated by tools/gen_tu_leaves.py from {sys.argv[1].split("/")[-1]} (sha256 {sha}). -/',
       '', 'set_option maxRecDepth 200000', '', 'namespace TUCore', '', 'open TPCore (Leaf)', '',
       '/-- The tiling runs from `45 / 400 = e₀` to `3526 / 400` (one node spacing past `e_N = 3525 / 400`). -/',
       'def leavesU : List Leaf := [']
items = [f'  ⟨{t[1]}, {t[2]}, {t[3]}, {t[4]}, {"true" if t[5] else "false"}, {t[6]}⟩' for t in L]
out.append(',\n'.join(items))
out += [']', '', 'end TUCore', '']
open(sys.argv[2], 'w').write('\n'.join(out))
print('leaves', len(L), 'sha', sha[:8])
