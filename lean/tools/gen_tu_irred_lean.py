#!/usr/bin/env python3
"""Generate TUN/Irred.lean (native_decide) and TUK/IrredK.lean (decide +kernel) from the certificate json of
tools/tu_irred_cert.py. Standard library only. Usage: python3 -I tools/gen_tu_irred_lean.py CERT.json TUN.lean TUK.lean"""
import json
import sys


def gen(res, track):
    tac = "native_decide" if track == "N" else "decide +kernel"
    suffix = "" if track == "N" else "_K"
    title = "N track: the checks by `native_decide`" if track == "N" else \
        "K track: each check by `decide +kernel`, one theorem per polynomial"
    out = []
    out.append("import TPUpper.IrredSound")
    out.append("import TPUpper.UDefs")
    out.append("import TUCore.IrredData")
    out.append("")
    out.append(f"/-! Irreducibility of the polynomials `Qc j` ({title}). Each `Q_j` is irreducible")
    out.append("modulo a small prime (`TUCore.irredPrimes`), certified by `TUCore.irredOK` and `TPUpper.irreducible_of_irredOK`.")
    out.append("Generated by tools/gen_tu_irred_lean.py. -/")
    out.append("")
    out.append("set_option maxRecDepth 100000")
    out.append("set_option maxHeartbeats 0")
    out.append("")
    out.append("open Polynomial")
    out.append("")
    out.append("namespace TPUpper.Cert")
    out.append("")
    out.append("open TUCore")
    out.append("")
    for r in res:
        j, p = r["j"], r["p"]
        out.append(f"theorem Qc_irred{suffix}_{j} : Irreducible (Qc ⟨{j}, by decide⟩) := by")
        out.append(f"  have : Fact (Nat.Prime {p}) := ⟨by norm_num⟩")
        out.append(f"  exact irreducible_of_irredOK {p} (TUCore.polys.getD {j} []) irredCert{j} (by {tac}) (by decide)")
        out.append("")
    out.append(f"/-- **All certificate polynomials are irreducible.** -/")
    out.append(f"theorem Qc_irred{suffix} : ∀ j, Irreducible (Qc j) := by")
    out.append("  rintro ⟨j, hj⟩")
    out.append(f"  have hj' : j < {len(res)} := hj")
    out.append("  interval_cases j")
    for r in res:
        out.append(f"  · exact Qc_irred{suffix}_{r['j']}")
    out.append("")
    out.append("end TPUpper.Cert")
    return "\n".join(out) + "\n"


def main():
    res = json.load(open(sys.argv[1]))
    open(sys.argv[2], "w").write(gen(res, "N"))
    open(sys.argv[3], "w").write(gen(res, "K"))


if __name__ == "__main__":
    main()
